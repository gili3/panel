import * as functionsV1 from "firebase-functions/v1";
import { db } from "../lib/admin";

/**
 * ELEVEN STORE — تنظيف بيانات المستخدم عند حذف الحساب
 * ═══════════════════════════════════════════════════════════════════════
 * لماذا هذا الـtrigger؟
 * ───────────────────────────────────────────────────────────────────────
 * حذف الحساب (سواء من الموقع Settings.tsx أو تطبيق الأندرويد
 * SettingsNotificationsScreens.kt) يحذف فقط سجل Firebase Auth نفسه
 * (`user.delete()`)، ولا ينظّف أي شيء في Firestore. بدون هذا الـtrigger
 * تبقى وثيقة `users/{uid}` وكل ما تحتها من عناوين وسلة ومفضلة وإشعارات
 * "يتيمة" في القاعدة للأبد — لا يملكها أحد ولا تُحذف أبداً، وهي بيانات
 * شخصية (عناوين، أرقام هواتف) يُفترض ألا تبقى بعد حذف صاحبها لحسابه.
 *
 * لماذا Cloud Function (auth trigger) وليس حذفاً مباشراً من العميل؟
 * ───────────────────────────────────────────────────────────────────────
 * حذف الحساب فعل حسّاس ونهائي؛ تنفيذه من الخادم (بعد تأكيد Firebase أن
 * الحذف الفعلي لحساب Auth قد تمّ فعلاً) هو المكان الوحيد الموثوق لضمان
 * "التنظيف يحدث دائماً"، بصرف النظر عن أي عطل شبكة على جهاز العميل بعد
 * نجاح استدعاء deleteUser() مباشرة، وبصرف النظر عن أي منصة (موقع أو
 * أندرويد) نفّذت الحذف. هذا يطابق تماماً فلسفة onOrderCreated/
 * onOrderStatusChanged بهذا المجلد: مصدر واحد للحقيقة بدل تكرار المنطق.
 *
 * ماذا يُحذف بالضبط، ولماذا؟
 * ───────────────────────────────────────────────────────────────────────
 * - وثيقة `users/{uid}` نفسها (تحوي: الاسم، الهاتف، الدور، fcmTokens).
 * - كل المجموعات الفرعية تحتها: cart، favorites، addresses، notifications
 *   — بيانات شخصية بحتة لا قيمة لها بعد حذف صاحبها، وتُحذف عبر
 *   recursiveDelete التي توفّرها Admin SDK لحذف شجرة كاملة بكل مستوياتها
 *   دفعة واحدة (وليس تكرار كل مجموعة فرعية يدوياً واحدة تلو الأخرى).
 *
 * ماذا لا يُحذف، ولماذا (قرار مقصود)؟
 * ───────────────────────────────────────────────────────────────────────
 * - مجموعة `orders` (الطلبات) بالكامل: طلبات المستخدم تبقى كما هي بكل
 *   تفاصيلها (بما فيها عنوان الشحن المحفوظ داخل كل طلب وقت إنشائه، ورابط
 *   إيصال الدفع في Storage). هذا قرار عمل متعمَّد: الطلبات سجلّات مالية/
 *   محاسبية لصاحب المتجر (تقارير المبيعات، الفواتير، أي التزام ضريبي أو
 *   نزاع دفع مستقبلي)، ولا يصحّ حذفها تلقائياً بمجرد حذف المستخدم لحسابه
 *   الشخصي — بخلاف عنوان "دفتر العناوين" الحالي الذي لا فائدة منه إطلاقاً
 *   بعد حذف الحساب. لو رغب صاحب المتجر مستقبلاً بسياسة مختلفة (مثال: حذف
 *   المعلومات الشخصية من الطلبات القديمة/أرشفتها بعد مدة معيّنة، أو حذفها
 *   بالكامل) فهذا قرار عمل/قانوني يحتاج تحديداً صريحاً، وليس افتراضاً
 *   يُتخذ ضمنياً هنا.
 */
export const onUserDeleted = functionsV1.auth.user().onDelete(async (user) => {
  const uid = user.uid;
  try {
    await db.recursiveDelete(db.collection("users").doc(uid));
  } catch (err) {
    // ✅ لا نرمي الخطأ هنا: فشل التنظيف بعد أن حُذف حساب Auth فعلاً (لا رجعة
    // فيه) يجب ألا يظهر كفشل "غامض" في سجلات Cloud Functions بلا سياق —
    // نسجّله بوضوح ليكون قابلاً للمتابعة يدوياً إن تكرر.
    console.error(`[onUserDeleted] فشل تنظيف بيانات المستخدم ${uid}:`, err);
  }
});
