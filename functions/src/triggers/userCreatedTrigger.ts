import * as functionsV1 from "firebase-functions/v1";
import { sendMail } from "../lib/mailer";
import { welcomeEmailTemplate } from "../lib/emailTemplates";

/**
 * ELEVEN STORE — رسالة ترحيب تلقائية عند إنشاء حساب جديد
 * ═══════════════════════════════════════════════════════════════════════
 * تعمل على أي حساب جديد بصرف النظر عن طريقة التسجيل (بريد/كلمة مرور أو
 * Google) لأنها auth trigger على مستوى Firebase Auth نفسه، لا على مسار
 * تسجيل محدَّد بكود العميل — بنفس فلسفة onUserDeleted (مصدر واحد للحقيقة
 * بدل تكرار الاستدعاء بكل شاشة تسجيل في كل منصة).
 * فشل الإرسال (تجاوز حصة Gmail اليومية مثلاً) لا يجب أن يظهر كخطأ غامض في
 * سجلات Cloud Functions بلا سياق، ولا يؤثر بأي شكل على نجاح إنشاء الحساب
 * نفسه (الذي تم فعلياً قبل استدعاء هذا الـtrigger أصلاً).
 *
 * ✅ إصلاح: كانت هذه الرسالة تُرسل لكل حساب جديد فوراً بصرف النظر عن حالة
 * التحقق. لحسابات البريد/كلمة المرور، هذا يعني إرسال رسالتين (ترحيب من
 * هنا + تأكيد من registerWithEmail بالعميل) من نفس حساب Gmail لنفس
 * المستلم الجديد خلال أجزاء من الثانية — نمط يُصنَّفه Gmail غالباً كسلوك
 * آلي/spam فيضع الترحيب في غير المهم، وأحياناً يُسقط رسالة التأكيد
 * (المُرسَلة ثانية بنفس الاتصال شبه المتزامن) بصمت. حسابات Google تصل
 * وتُنشأ بالفعل بـ`emailVerified: true` فرسالة واحدة فقط (ترحيب) تُرسل
 * لها — ولهذا كانت تصل دائماً بلا مشاكل، بعكس البريد/كلمة المرور.
 * الحل: لا نرسل الترحيب هنا إلا للحسابات المؤكَّدة بالفعل عند الإنشاء
 * (Google وأي مزوّد آخر مُتحقَّق منه مسبقاً). حسابات البريد/كلمة المرور
 * غير المؤكَّدة تستلم رسالة واحدة فقط الآن (تأكيد + ترحيب مدمَج في نفس
 * القالب، انظر verifyEmailTemplate) — رسالة واحدة بدل اثنتين، فلا يوجد
 * سباق إرسال من الأساس.
 */
export const onUserCreated = functionsV1.auth.user().onCreate(async (user) => {
  if (!user.email) return;
  if (!user.emailVerified) return; // ستصل رسالة الترحيب مدمجة مع رسالة التأكيد
  try {
    const { subject, html } = welcomeEmailTemplate(user.displayName || "");
    await sendMail({ to: user.email, subject, html });
  } catch (err) {
    console.error(`[onUserCreated] فشل إرسال رسالة الترحيب لـ ${user.uid}:`, err);
  }
});
